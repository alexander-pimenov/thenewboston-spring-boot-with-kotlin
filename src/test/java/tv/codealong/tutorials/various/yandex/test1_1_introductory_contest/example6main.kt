package tv.codealong.tutorials.various.yandex.test1_1_introductory_contest

import java.io.File


/**
 * Даны две строки строчных латинских символов:
 * строка J и строка S.
 * Символы, входящие в строку J, — «драгоценности», входящие в строку S — «камни».
 * Нужно определить, какое количество символов из S одновременно являются «драгоценностями».
 * Проще говоря, нужно проверить, какое количество символов из S входит в J.
 *
 * Это разминочная задача, к которой мы размещаем готовые решения.
 * Она очень простая и нужна для того, чтобы вы могли познакомиться с нашей автоматической системой проверки решений. Ввод и вывод осуществляется через файлы, либо через стандартные потоки ввода-вывода, как вам удобнее.
 *
 * Процесс:
 * J = "ab" → драгоценности: {'a', 'b'}
 * S = "abcdeabb" → проверяем каждый символ:
 * 'a' - драгоценность ✓
 * 'b' - драгоценность ✓
 * 'c' - нет ✗
 * 'd' - нет ✗
 * 'e' - нет ✗
 * 'a' - драгоценность ✓
 * 'b' - драгоценность ✓
 * 'b' - драгоценность ✓
 * Итого: 6 драгоценностей
 *
 * Рекомендации для собеседования:
 * - Используй Set - это показывает понимание эффективных структур данных
 * - Обрабатывай исключения - файлы могут не существовать
 * - Проверяй входные данные - что строки не null, файл содержит 2 строки
 * - Объясни сложность - почему O(J + S) лучше чем O(J × S)
 */
fun main(args: Array<String>) {
    val j = readLine()!!
    val s = readLine()!!

    var result = 0
    for (c in s) {
        if (j.contains(c)) {
            result += 1;
        }
    }

    println(result)
}

/**
 *  J = "ab" → драгоценности: {'a', 'b'}
 *  S = "abcdeabb"
 */
fun checkChars() {
    try {
        val lines = File("input.txt").readLines()
        if (lines.size < 2) {
            println("Ошибка: файл должен содержать две строки")
            return
        }

        val J = lines[0]
        val S = lines[1]

        val jewels = J.toSet()
        val count = S.count { it in jewels }

        File("output.txt").writeText(count.toString())
        println("Результат: $count")

    } catch (e: Exception) {
        println("Ошибка: ${e.message}")
    }
}