 *             1 -> { // Добавить число y после x-ого элемента
 *                 val x = scanner.nextInt()
 *                 val y = scanner.nextInt()
 *
 *                 if (x == 0) {
 *                     list.addFirst(y)
 *                 } else {
 *                     // Вставляем на позицию x (в 1-based индексации)
 *                     // В 0-based индексации это позиция x
 *                     list.add(x, y)
 *                 }
 *             }
 *             2 -> { // Вывести число на позиции x
 *                 val x = scanner.nextInt()
