 *  Алгоритм:
 *   - Используем LinkedList для эффективных операций вставки/удаления в середине
 *   - Обрабатываем три типа запросов: добавление, вывод и удаление
 *   - Конвертируем индексы из 1-based (задача) в 0-based (Kotlin)
 *
 *   Примечание: Пусть size_i - размер списка в момент i-ого запроса.
 *   Гарантируется, что все операции корректны (достаточно элементов).
 *
 *   Сложность:
 *   - Вставка: O(1) для LinkedList при известной позиции
 *   - Удаление: O(1) для LinkedList при известной позиции
 *   - Получение: O(n) в худшем случае, но операций получения меньше
