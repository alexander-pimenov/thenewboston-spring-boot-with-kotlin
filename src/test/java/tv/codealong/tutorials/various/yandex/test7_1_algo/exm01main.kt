import java.util.*

fun main() {
    val scanner = Scanner(System.`in`)
    val q = scanner.nextInt() // Количество запросов

    // LinkedList выбран для эффективных операций вставки/удаления в середине
    val list = LinkedList<Int>()
    val output = StringBuilder()

    repeat(q) {
        val operation = scanner.nextInt() // Тип операции: 1, 2 или 3

        when (operation) {
            1 -> {
                // ЗАПРОС 1: Добавить число y после x-ого элемента
                // Если x = 0 - добавить в начало списка
                val x = scanner.nextInt() // Позиция (1-based)
                val y = scanner.nextInt() // Значение для добавления

                if (x == 0) {
                    // Добавляем в начало списка
                    list.addFirst(y)
                } else {
                    // Вставляем на позицию x (в 1-based индексации)
                    // В 0-based индексации это позиция x
                    list.add(x, y)
                }
                // После операции: размер списка увеличился на 1
                // size_i = size_{i-1} + 1
            }

            2 -> {
                // ЗАПРОС 2: Вывести число на позиции x
                val x = scanner.nextInt() // Позиция (1-based)
                // Переводим из 1-based в 0-based
                output.append("${list[x - 1]}\n")
                // Размер списка не меняется
                // size_i = size_{i-1}
            }

            3 -> {
                // ЗАПРОС 3: Удалить число на позиции x
                val x = scanner.nextInt() // Позиция (1-based)
                // Переводим из 1-based в 0-based
                list.removeAt(x - 1)
                // После операции: размер списка уменьшился на 1
                // size_i = size_{i-1} - 1
            }
        }

        // Для отладки можно раскомментировать:
        // println("После операции $operation: $list")
    }
    // Выводим все результаты запросов типа 2
    print(output)
}