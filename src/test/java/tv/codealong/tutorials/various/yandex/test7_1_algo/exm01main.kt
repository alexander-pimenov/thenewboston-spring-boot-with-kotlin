 *
 * 2. **Операция "добавить после x-ого"**:
 *    - Если x=0 - добавляем в начало
 *    - Если x=1 - добавляем после первого элемента (становится вторым)
 *
 * 3. **LinkedList хорошо подходит**, потому что операции вставки/удаления в середине эффективны
