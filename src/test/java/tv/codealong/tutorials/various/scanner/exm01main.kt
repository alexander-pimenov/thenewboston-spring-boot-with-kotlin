package tv.codealong.tutorials.various.scanner

import java.util.Scanner

/**
 * Давай разберем, как работает `Scanner.nextInt()`.
 *
 * ## Как работает Scanner.nextInt()
 *
 * `Scanner.nextInt()` читает данные **по токенам (словам)**, а не посимвольно или построчно.
 *
 * ### Принцип работы:
 *
 * 1. **Пропускает все "пробельные символы"** (whitespace) до первого непробельного символа
 *    - Пробельные символы: пробелы, табуляции, переводы строк
 *
 * 2. **Читает последовательность цифр** до первого непробельного символа, который не является цифрой
 *
 * 3. **Преобразует эту последовательность в число**
 *
 * ### Пример:
 *
 * ```kotlin
 * val input = "   123  456\n789"
 * val scanner = Scanner(input)
 *
 * println(scanner.nextInt()) // 123 (пропустил пробелы, прочитал 123)
 * println(scanner.nextInt()) // 456 (пропустил пробелы, прочитал 456)
 * println(scanner.nextInt()) // 789 (пропустил \n, прочитал 789)
 * ```
 *
 * ### В нашей задаче:
 *
 * ```
 * 8
 * 1 0 5
 * 2 1
 * ...
 * ```
 *
 * **Как это обрабатывается:**
 *
 * ```kotlin
 * val q = scanner.nextInt() // Читает "8" (первое число)
 * // Scanner теперь стоит после "8", перед переводом строки
 *
 * repeat(q) {
 *     val operation = scanner.nextInt() // Пропускает перевод строки и пробелы, читает "1"
 *     // Дальше в зависимости от operation читаем x и y
 * }
 * ```
 *
 * ### Визуализация для первого запроса:
 *
 * **Данные:** `"1 0 5"`
 *
 * ```kotlin
 * scanner.nextInt() // ↑1 0 5 → 1↑ 0 5 (вернул 1, курсор после "1")
 * scanner.nextInt() // 1 ↑0 5 → 1 0↑ 5 (вернул 0, курсор после "0")
 * scanner.nextInt() // 1 0 ↑5 → 1 0 5↑ (вернул 5, курсор после "5")
 * ```
 *
 * ### Важные особенности:
 *
 * - **Автоматически пропускает пробелы и переводы строк** между токенами
 * - **Не читает пустые строки** как отдельные токены
 * - **Работает с любым количеством пробелов** между числами
 *
 * ### Альтернатива для построчного чтения:
 *
 * Если бы нужно было читать именно построчно, можно было бы так:
 *
 * ```kotlin
 * val q = readLine()!!.toInt()
 * repeat(q) {
 *     val line = readLine()!!.split(" ")
 */
fun main() {
    val input = "   123  456\n789"
    val scanner = Scanner(input)

    println(scanner.nextInt()) // 123 (пропустил пробелы, прочитал 123)
    println(scanner.nextInt()) // 456 (пропустил пробелы, прочитал 456)
    println(scanner.nextInt()) // 789 (пропустил \n, прочитал 789)

    val q = readLine()!!.toInt()
    repeat(q) {
        val line = readLine()!!.split(" ") // Читаем построчно
        println("размер массива: ${line.size}. Элементы: $line") // Выводим для наглядности
    }
}