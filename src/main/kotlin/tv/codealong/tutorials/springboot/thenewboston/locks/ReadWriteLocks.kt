package tv.codealong.tutorials.springboot.thenewboston.locks

import java.util.concurrent.locks.ReentrantReadWriteLock
import kotlin.concurrent.*

class ReadWriteLocks {
}

val rwLock = ReentrantReadWriteLock()
fun readData() {
    rwLock.readLock().lock()
    try {
        // Read operation
    } finally {
        rwLock.readLock().unlock()
    }
}

fun writeData() {
    rwLock.writeLock().lock()
    try {
        // Write operation
    } finally {
        rwLock.writeLock().unlock()
    }
}


/**
 * Пример
 * https://www.javaspecialists.eu/archive/Issue279-Upgrading-ReadWriteLock.html
 * Основные моменты:
 *
 *     write lock блокирует все другие операции — как чтение, так и запись другими потоками.
 *     read lock позволяет нескольким потокам читать одновременно, но блокирует запись.
 *     Важно, что внутри одного потока можно захватывать как read lock, так и write lock, что делает возможным совмещение операций чтения и записи внутри одного потока.
 *     ReentrantReadWriteLock позволяет одному потоку повторно захватывать те же блокировки, если они уже удерживаются этим же потоком, благодаря механизму реентрантности.
 *
 * Таким образом, этот код демонстрирует, как можно комбинировать чтение и запись в одном потоке при использовании ReentrantReadWriteLock.
 */
fun main() {
    //В начале блокировки rwlock1, оба счётчика w (запись) и r (чтение) равны нулю (w=0, r=0), что значит, что никто не захватил блокировку на чтение или запись.
    //
    //Вызывается блок write, который захватывает write lock (w=1, r=0). Это значит, что поток получил доступ на запись, и другие потоки не смогут ни читать, ни писать, пока блокировка не будет снята.
    //
    //Внутри блока записи вызывается блок read, который пытается захватить read lock. Несмотря на то, что уже захвачена запись, это возможно, потому что запись и чтение в одном и том же потоке могут совмещаться. Блокировка на чтение захватывается, и теперь мы видим состояние w=1, r=1 — блокировка на запись сохраняется, но внутри есть разрешённое чтение.
    //
    //После завершения блока чтения блокировка на чтение освобождается (w=1, r=0), но блокировка на запись остаётся.
    //
    //После завершения блока записи блокировка на запись освобождается полностью (w=0, r=0), и ресурс снова свободен.
    val rwlock1 = ReentrantReadWriteLock()
    println(rwlock1) // w=0, r=0
    rwlock1.write {
        println(rwlock1) // w=1, r=0
        rwlock1.read {
            println(rwlock1) // w=1, r=1
        }
        println(rwlock1) // w=1, r=0
    }
    println(rwlock1) // w=0, r=0

    //-----------------------------
    //Начальное состояние блокировки rwlock2: w=0, r=0 — никто не захватил блокировку.
    //
    //Блок read захватывает read lock, и мы видим состояние w=0, r=1. Это означает, что текущий поток читает, и другие потоки могут также читать (если такие будут).
    //
    //Внутри блока чтения вызывается блок write. Это возможно только потому, что данный поток внутри своего блока чтения может захватить запись. Сначала снимается read lock (поэтому состояние становится w=1, r=0), и поток получает доступ на запись.
    //
    //После завершения блока записи блокировка на запись снимается, но read lock автоматически восстанавливается для исходного блока чтения. Это видно в выводе w=0, r=1.
    //
    //После завершения блока чтения блокировка полностью освобождается: w=0, r=0.
    val rwlock2 = ReentrantReadWriteLock()
    println(rwlock2) // w=0, r=0
    rwlock2.read {
        println(rwlock2) // w=0, r=1
        rwlock2.write {
            println(rwlock2) // w=1, r=0
        }
        println(rwlock2) // w=0, r=1
    }
    println(rwlock2) // w=0, r=0
}
