package tv.codealong.tutorials.springboot.thenewboston.utils

import org.springframework.stereotype.Component

/**
 * Разберём, что собой представляет конструкция `object` в Kotlin и как она
 * ведет себя в контексте Spring Framework.
 *
 * ---
 *
 * ## Объекты Kotlin (`object`)
 *
 * Конструкция `object` в Kotlin называется **объектом-компаньоном (singleton)**.
 * Это специальная форма одиночных экземпляров, созданных самим языком.
 * Объект создаётся **только один раз** и существует ровно столько, сколько живёт
 * программа.
 *
 * ### Особенности объекта:
 *
 * - **Singleton**: Только один экземпляр класса, гарантированная уникальность.
 * - **Ленивая инициализация**: Объект создается только тогда, когда впервые к
 * нему обращается программа.
 * - **Глобальная область видимости**: Один экземпляр доступен везде, где видима
 * его декларация.
 *
 * ---
 *
 * ## Создание объекта:
 *
 * Объект в Kotlin создаётся автоматически **при первом обращении к нему**.
 * Это значит, что при старте приложения или первого вызова любого метода объекта
 * он лениво инициализируется.
 *
 * Пример:
 *
 * ```kotlin
 * object MySingleton {
 *     init {
 *         println("Инициализация объекта!")
 *     }
 *
 *     fun hello() {
 *         println("Hello from Singleton!")
 *     }
 * }
 *
 * // Вызываем первый раз
 * MySingleton.hello() // Тут произойдет инициализация
 * ```
 *
 * До первого вызова объекта он не будет существовать физически, но как
 * только мы попытаемся вызвать его метод, произойдёт инициализация.
 *
 * ---
 *
 * ## Где хранится объект?
 *
 * Хотя Kotlin-классы объявляются как объекты (`object`), они не хранятся
 * напрямую в Spring IoC-контейнере. Однако если этот объект объявлен с аннотацией
 * `@Component` или аналогичным образом, то Spring увидит его и зарегистрирует в
 * своём контейнере как bean (экземпляр сервиса).
 *
 * Пример:
 *
 * ```kotlin
 * @Component
 * object MySingleton {
 *     fun hello() {
 *         println("Hello from Singleton!")
 *     }
 * }
 * ```
 *
 * Теперь Spring найдёт этот объект и внесёт его в контейнер как полноценный bean,
 * несмотря на то, что технически он уже является singleton-ом.
 *
 * ---
 *
 * ## Хранение в Spring IoC:
 *
 * Когда объект регистрируется в Spring IoC-контейнере, он превращается в
 * стандартный bean, и обращение к нему происходит через обычный механизм
 * внедрения зависимостей. Это значит, что хотя технически объект создан языком,
 * его использование ничем не отличается от обычного bean-а в Spring.
 *
 * ---
 *
 * ## Важные моменты:
 *
 * - Объект Kotlin всегда гарантированно один, вне зависимости от количества инъекций
 * или обращений.
 * - Если он аннотирован как `@Component`, Spring создаст ссылку на него в своём
 * контейнере, и обращаться к нему можно как к обычному bean-у.
 *
 * ---
 *
 * ## Заключение:
 *
 * Объект Kotlin создаётся лениво при первом обращении и существует единожды в
 * программе. Если он аннотирован `@Component`, он попадает в Spring IoC-контейнер
 * и используется как обычный bean.
 */
@Component
object MySingletonComponent {
    init {
        println("Инициализация объекта MySingletonComponent! - ${this.javaClass}")
    }

    fun hello() {
        println("Hello from MySingletonComponent!")
    }
}