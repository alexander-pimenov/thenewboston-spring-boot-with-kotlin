package tv.codealong.tutorials.various.backoff_strategy

/**
 * **Backoff-стратегия** — это подход, который используется в многопоточных и распределённых
 * системах, чтобы избежать конфликтов при доступе к общим ресурсам, особенно когда возникает
 * конкуренция или ошибки.
 *
 * ---
 *
 * ### 🔄 Что такое Backoff?
 *
 * **Backoff (откат, отступление)** — это стратегия, при которой поток или процесс,
 * столкнувшись с неудачей (например, не смог захватить ресурс), **не пытается сразу снова**,
 * а **ждёт некоторое время**, прежде чем повторить попытку.
 *
 * ---
 *
 * ### 🧠 Зачем это нужно?
 *
 * - Уменьшает вероятность взаимной блокировки (deadlock).
 * - Снижает нагрузку на систему.
 * - Предотвращает «шторм» запросов, когда все потоки одновременно пытаются получить доступ.
 *
 * ---
 *
 * ### 📊 Виды Backoff-стратегий
 *
 * | Стратегия              | Описание                                                                 |
 * |------------------------|--------------------------------------------------------------------------|
 * | **Fixed Backoff**      | Поток ждёт фиксированное время перед повторной попыткой.                |
 * | **Random Backoff**     | Поток ждёт случайное время в заданном диапазоне.                        |
 * | **Exponential Backoff**| Время ожидания увеличивается экспоненциально с каждой неудачей.         |
 * | **Jitter Backoff**     | Добавляется случайный разброс к экспоненциальному ожиданию (для гибкости).|
 *
 * ---
 *
 * ### 🧪 Пример Exponential Backoff на Kotlin
 *
 * ```kotlin
 * fun exponentialBackoff(attempt: Int): Long {
 *     val baseDelay = 100L // миллисекунды
 *     val maxDelay = 2000L
 *     val delay = baseDelay * (1 shl attempt)
 *     return minOf(delay, maxDelay)
 * }
 *
 * fun main() {
 *     for (attempt in 0..5) {
 *         val waitTime = exponentialBackoff(attempt)
 *         println("Попытка $attempt: ждём $waitTime мс перед повтором")
 *         Thread.sleep(waitTime)
 *     }
 * }
 * ```
 *
 * ---
 *
 * ### 📌 Где применяется:
 * - Сетевые запросы (например, повторная отправка при ошибке).
 * - Захват блокировок в многопоточности.
 * - Работа с базами данных.
 * - API-интеграции, особенно при ограничениях по частоте.
 *
 * Если хочешь, я могу показать, как встроить такую стратегию в поток с `ReentrantLock` или
 * в сетевой запрос.
 */
fun exponentialBackoff(attempt: Int): Long {
    val baseDelay = 100L // миллисекунды
    val maxDelay = 2000L
    val delay = baseDelay * (1 shl attempt)
    return minOf(delay, maxDelay)
}

fun main() {
    for (attempt in 0..5) {
        val waitTime = exponentialBackoff(attempt)
        println("Попытка $attempt: ждём $waitTime мс перед повтором")
        Thread.sleep(waitTime)
    }
}
